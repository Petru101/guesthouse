//! The calls of the driver's memory module. Their numbers carry no size, so the guest needs a table.

use super::{COMMON_INCLUDES, PROGRAM_END, PROGRAM_START, include_flag, measure, read_text, sdk};
use crate::failure::Result;
use regex::Regex;
use std::collections::BTreeMap;
use std::path::Path;

const MODULE_FOLDER: &str = "kernel-open/nvidia-uvm";
const CALL_HEADERS: [&str; 2] = ["uvm_ioctl.h", "uvm_linux_ioctl.h"];
const HEADER: &str = "/* Generated by Guesthouse. number, parameter size, offset of an fd or -1 */\n";
const NUMBERED: &str = r"#define\s+(UVM_\w+)\s+UVM_IOCTL_BASE\((\d+)\)";
const PARAMETERS: &str = r"(?s)^ struct\s*\w*\s*\{(.*?)\}\s*(UVM_\w+_PARAMS);";
const FILE_FIELD: &str = r"\b(rmCtrlFd|uvmFd)\b";
const SKIPPED_MARK: &str = "_BACKING";
/// The first call, which isn't numbered like the rest.
const FIRST_CALL: (&str, &str) = ("UVM_INITIALIZE", "0x30000001");

fn numbered_calls(text: &str) -> Vec<(String, String)> {
    let numbered = Regex::new(NUMBERED).unwrap();
    let mut found: Vec<(u32, String)> = numbered
        .captures_iter(text)
        .filter_map(|parts| Some((parts[2].parse().ok()?, parts[1].to_owned())))
        .collect();
    found.sort();
    found.dedup();
    found.into_iter().map(|(number, name)| (name, number.to_string())).collect()
}

/// Each struct's body, by name. The body of one never reaches into the next, so each `typedef` is
/// looked at on its own.
fn parameter_structs(text: &str) -> BTreeMap<String, String> {
    let parameters = Regex::new(PARAMETERS).unwrap();
    let parts = text.split("typedef").skip(1);
    parts
        .filter_map(|part| {
            let found = parameters.captures(part)?;
            Some((found[2].to_owned(), found[1].to_owned()))
        })
        .collect()
}

fn measuring_line(name: &str, number: &str, structs: &BTreeMap<String, String>) -> Option<String> {
    let kind = format!("{name}_PARAMS");
    let body = structs.get(&kind).filter(|_| !kind.contains(SKIPPED_MARK))?;
    let field = Regex::new(FILE_FIELD).unwrap().find(body);
    let offset =
        field.map_or("(size_t)-1".to_owned(), |found| format!("offsetof({kind},{})", found.as_str()));
    Some(format!("printf(\"{{ {number}, %zu, %d }}, /* {name} */\\n\", sizeof({kind}), (int){offset});\n"))
}

pub fn table(tree: &Path, work: &Path) -> Result<String> {
    let folder = tree.join(MODULE_FOLDER);
    let mut text = String::new();
    for name in CALL_HEADERS {
        text.push_str(&read_text(&folder.join(name))?);
    }
    let structs = parameter_structs(&text);
    let mut calls = numbered_calls(&text);
    calls.push((FIRST_CALL.0.to_owned(), FIRST_CALL.1.to_owned()));
    let lines: String =
        calls.iter().filter_map(|(name, number)| measuring_line(name, number, &structs)).collect();
    let source = format!(
        "{COMMON_INCLUDES}#include \"uvm_types.h\"\n#include \"uvm_ioctl.h\"\n#include \"uvm_linux_ioctl.h\"\n\
         {PROGRAM_START}{lines}{PROGRAM_END}"
    );
    let flags = vec![
        include_flag(&sdk(tree)),
        include_flag(&folder),
        include_flag(&tree.join("kernel-open/common/inc")),
    ];
    Ok(format!("{HEADER}{}", measure(work, &source, &flags)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    const CALLS: &str = "
        #define UVM_LATE UVM_IOCTL_BASE(20)
        #define UVM_EARLY UVM_IOCTL_BASE(3)
        typedef struct { NvU32 count; } UVM_EARLY_PARAMS;
        typedef struct { NvS32 rmCtrlFd; } UVM_LATE_PARAMS;
        typedef NvU32 Other;
        typedef struct { NvU32 kept; } UVM_ODD_BACKING_PARAMS;";

    #[test]
    fn calls_come_in_number_order() {
        let found = numbered_calls(CALLS);
        assert_eq!(found[0], ("UVM_EARLY".to_owned(), "3".to_owned()));
        assert_eq!(found[1], ("UVM_LATE".to_owned(), "20".to_owned()));
    }

    #[test]
    fn a_struct_says_whether_it_holds_a_file() {
        let structs = parameter_structs(CALLS);
        assert!(measuring_line("UVM_EARLY", "3", &structs).unwrap().contains("(size_t)-1"));
        let late = measuring_line("UVM_LATE", "20", &structs).unwrap();
        assert!(late.contains("offsetof(UVM_LATE_PARAMS,rmCtrlFd)"));
    }

    #[test]
    fn calls_with_no_struct_or_a_skipped_one_are_left_out() {
        let structs = parameter_structs(CALLS);
        assert_eq!(measuring_line("UVM_NONE", "9", &structs), None);
        assert_eq!(measuring_line("UVM_ODD_BACKING", "9", &structs), None);
    }
}
