//! How big each class's allocation parameters are. A caller may give a size of 0, and the driver then
//! takes it from its own list, so the guest needs that list too.

use super::{
    COMMON_INCLUDES, PROGRAM_END, PROGRAM_START, files_under, include_flag, includes, measure, read_text, sdk,
};
use crate::failure::Result;
use regex::Regex;
use std::collections::BTreeSet;
use std::path::Path;

const RESOURCE_LIST: &str = "src/nvidia/src/kernel/rmapi/resource_list.h";
const HEADER: &str = "/* Generated by Guesthouse. class, allocation parameter size */\n";
const ENTRY_START: &str = "RS_ENTRY(";
const ENTRY: &str =
    r"(?s)External Class\s*\*/\s*(\w+),.*?Alloc Param Info\s*\*/\s*RS_(?:OPTIONAL|REQUIRED)\((\w+)\)";
/// The folders holding class headers.
const FOLDERS: [&str; 2] = ["class", "alloc"];
/// Headers of a class number, deeper than the top of a folder, have nothing a class needs.
const NUMBERED_HEADER: &str = r"cl[0-9a-f]+(_callback|sw)?.h$";
/// A type the headers don't have to define.
const PLAIN_HANDLE: &str = "NvHandle";

fn entries_in(text: &str) -> Vec<(String, String)> {
    let entry = Regex::new(ENTRY).unwrap();
    let parts = text.split(ENTRY_START).skip(1);
    parts
        .filter_map(|part| {
            let found = entry.captures(part)?;
            Some((found[1].to_owned(), found[2].to_owned()))
        })
        .collect()
}

fn headers_for_classes(sdk: &Path) -> Vec<String> {
    let numbered = Regex::new(NUMBERED_HEADER).unwrap();
    let mut chosen = BTreeSet::new();
    for folder in FOLDERS {
        let mut found = Vec::new();
        files_under(sdk, folder, &mut found);
        found.retain(|name| name.ends_with(".h"));
        let at_top = |name: &String| name.matches('/').count() == 1;
        chosen.extend(found.into_iter().filter(|name| at_top(name) || !numbered.is_match(name)));
    }
    chosen.into_iter().collect()
}

fn is_public(class: &str, kind: &str, headers: &str) -> bool {
    let defined = Regex::new(&format!(r"define\s+{class}\b")).unwrap();
    let named = Regex::new(&format!(r"\b{kind}\b")).unwrap();
    defined.is_match(headers) && (kind == PLAIN_HANDLE || named.is_match(headers))
}

pub fn table(tree: &Path, work: &Path) -> Result<String> {
    let sdk = sdk(tree);
    let names = headers_for_classes(&sdk);
    let mut headers = read_text(&sdk.join("nvos.h"))?;
    for name in &names {
        headers.push_str(&read_text(&sdk.join(name))?);
    }
    let entries = entries_in(&read_text(&tree.join(RESOURCE_LIST))?);
    let public = entries.iter().filter(|(class, kind)| is_public(class, kind, &headers));
    let lines: String = public
        .map(|(class, kind)| {
            format!(
                "printf(\"{{ 0x%x, %zu }}, /* {class} {kind} */\\n\", (unsigned){class}, sizeof({kind}));\n"
            )
        })
        .collect();
    let source = format!(
        "{COMMON_INCLUDES}#include \"nvos.h\"\n{}{PROGRAM_START}{lines}{PROGRAM_END}",
        includes(&names)
    );
    let flags = vec![include_flag(&sdk), include_flag(&tree.join("src/common/inc"))];
    Ok(format!("{HEADER}{}", measure(work, &source, &flags)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_class_comes_with_its_parameter_type() {
        let text = "RS_ENTRY(
            /* External Class */ ONE_CLASS,
            /* Alloc Param Info */ RS_REQUIRED(ONE_PARAMS),
        )
        RS_ENTRY(
            /* External Class */ NO_PARAMS_CLASS,
            /* Alloc Param Info */ RS_NONE,
        )";
        assert_eq!(entries_in(text), [("ONE_CLASS".to_owned(), "ONE_PARAMS".to_owned())]);
    }

    #[test]
    fn a_class_needs_its_name_and_type_in_the_headers() {
        let headers = "#define ONE_CLASS 1\nstruct ONE_PARAMS;";
        assert!(is_public("ONE_CLASS", "ONE_PARAMS", headers));
        assert!(is_public("ONE_CLASS", PLAIN_HANDLE, headers));
        assert!(!is_public("TWO_CLASS", "ONE_PARAMS", headers));
        assert!(!is_public("ONE_CLASS", "TWO_PARAMS", headers));
    }
}
