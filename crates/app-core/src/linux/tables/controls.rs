//! Which controls hold pointers to more data, and where.

use super::{
    COMMON_INCLUDES, PROGRAM_END, PROGRAM_START, files_under, include_flag, includes, measure, read_text, sdk,
};
use crate::failure::Result;
use regex::Regex;
use std::path::Path;

const COPIES_FILE: &str = "src/nvidia/src/kernel/rmapi/embedded_param_copy.c";
const HEADER: &str = "/* Generated by Guesthouse from NVIDIA's MIT-licensed public source. */\n\
                      /* cmd, pointer offset, count offset, count size, element size */\n";
const CASE: &str = r"(?s)case (NV\w+):\s*\{(.*?)break;";
const COPY: &str = r"(?s)RMAPI_PARAM_COPY_INIT\(paramCopies\[\d\],\s*\(\((\w+)\s*\*\)pParams\)->(\w+),\s*\(\(\w+\s*\*\)pParams\)->\w+,\s*\(\(\w+\s*\*\)pParams\)->(\w+),\s*([^;]*?)\);";

struct Copy {
    control: String,
    kind: String,
    field: String,
    count: String,
    element: String,
}

fn copies_in(text: &str) -> Vec<Copy> {
    let (case, copy) = (Regex::new(CASE).unwrap(), Regex::new(COPY).unwrap());
    let mut found = Vec::new();
    for control in case.captures_iter(text) {
        for parts in copy.captures_iter(&control[2]) {
            found.push(Copy {
                control: control[1].to_owned(),
                kind: parts[1].to_owned(),
                field: parts[2].to_owned(),
                count: parts[3].to_owned(),
                element: parts[4].trim().to_owned(),
            });
        }
    }
    found
}

/// A control that the public headers don't name can't be allowed, as nothing can measure it.
fn is_public(copy: &Copy, headers: &str) -> bool {
    let defined = Regex::new(&format!(r"define\s+{}\b", copy.control)).unwrap();
    headers.contains(&copy.kind) && defined.is_match(headers)
}

fn measuring_line(copy: &Copy) -> String {
    let Copy { control, kind, field, count, element } = copy;
    format!(
        "printf(\"{{ 0x%08x, %zu, %zu, %zu, %zu }}, /* {control}.{field} */\\n\", (unsigned){control}, \
         offsetof({kind},{field}), offsetof({kind},{count}), sizeof((({kind}*)0)->{count}), (size_t)({element}));\n"
    )
}

pub fn table(tree: &Path, work: &Path) -> Result<String> {
    let sdk = sdk(tree);
    let mut names = Vec::new();
    files_under(&sdk, "ctrl", &mut names);
    names.retain(|name| {
        name.rsplit('/').next().is_some_and(|file| file.starts_with("ctrl") && file.ends_with(".h"))
    });
    let mut headers = String::new();
    for name in &names {
        headers.push_str(&read_text(&sdk.join(name))?);
    }
    let copies = copies_in(&read_text(&tree.join(COPIES_FILE))?);
    let lines: String = copies.iter().filter(|copy| is_public(copy, &headers)).map(measuring_line).collect();
    let source = format!(
        "{COMMON_INCLUDES}#include \"nvos.h\"\n{}{PROGRAM_START}{lines}{PROGRAM_END}",
        includes(&names)
    );
    let flags = vec![
        "-fpermissive".to_owned(),
        include_flag(&sdk),
        include_flag(&sdk.join("ctrl")),
        include_flag(&tree.join("src/common/inc")),
        include_flag(&tree.join("src/nvidia/inc")),
    ];
    Ok(format!("{HEADER}{}", measure(work, &source, &flags)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    const COPIES: &str = "
        case NV_CTRL_ONE:
        {
            RMAPI_PARAM_COPY_INIT(paramCopies[0],
                ((ONE_PARAMS *)pParams)->list,
                ((ONE_PARAMS *)pParams)->list,
                ((ONE_PARAMS *)pParams)->count, sizeof(NvU32) );
            break;
        }
        case NV_CTRL_EMPTY:
        {
            break;
        }";

    #[test]
    fn a_control_with_a_pointer_is_found_with_its_parts() {
        let found = copies_in(COPIES);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].control, "NV_CTRL_ONE");
        assert_eq!(found[0].kind, "ONE_PARAMS");
        assert_eq!((found[0].field.as_str(), found[0].count.as_str()), ("list", "count"));
        assert_eq!(found[0].element, "sizeof(NvU32)");
    }

    #[test]
    fn what_the_headers_lack_is_left_out() {
        let copy = &copies_in(COPIES)[0];
        assert!(is_public(copy, "#define NV_CTRL_ONE 1\ntypedef struct ONE_PARAMS {} ONE_PARAMS;"));
        assert!(!is_public(copy, "#define NV_CTRL_ONE_MORE 1\ntypedef struct ONE_PARAMS {} ONE_PARAMS;"));
        assert!(!is_public(copy, "#define NV_CTRL_ONE 1\n"));
    }
}
